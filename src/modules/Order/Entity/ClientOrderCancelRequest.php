namespace Box\Mod\Order\Entity;

use Box\Mod\Client\Entity\Client;
use Doctrine\DBAL\Types\Types;
use Doctrine\ORM\Mapping as ORM;
use FOSSBilling\Core\Doctrine\TimestampInterface;
use FOSSBilling\Core\Doctrine\TimestampTrait;

#[ORM\Entity(repositoryClass: \Box\Mod\Order\Repository\ClientOrderCancelRequestRepository::class)]
#[ORM\Table(name: 'client_order_cancel_request')]
#[ORM\Index(name: 'client_order_cancel_request_order_id_idx', columns: ['client_order_id'])]
#[ORM\Index(name: 'client_order_cancel_request_status_idx', columns: ['status'])]
#[ORM\HasLifecycleCallbacks]
class ClientOrderCancelRequest implements TimestampInterface
{
    use TimestampTrait;

    final public const string TYPE_IMMEDIATE = 'immediate';
    final public const string TYPE_END_OF_PERIOD = 'end_of_period';

    final public const string STATUS_PENDING = 'pending';
    final public const string STATUS_ACCEPTED = 'accepted';
    final public const string STATUS_STOPPED = 'stopped';
    final public const string STATUS_WITHDRAWN = 'withdrawn';

    #[ORM\Id]
    #[ORM\GeneratedValue]
    #[ORM\Column(type: Types::BIGINT)]
    /** @phpstan-ignore property.unusedType (Doctrine entity ID is auto-generated by the database) */
    private ?int $id = null;

    #[ORM\ManyToOne(targetEntity: Order::class)]
    #[ORM\JoinColumn(name: 'client_order_id', referencedColumnName: 'id', nullable: true)]
    private ?Order $order = null;

    #[ORM\ManyToOne(targetEntity: Client::class)]
    #[ORM\JoinColumn(name: 'client_id', referencedColumnName: 'id', nullable: true)]
    private ?Client $client = null;

    #[ORM\Column(type: Types::STRING, length: 32, nullable: true)]
    private ?string $type = null;

    #[ORM\Column(type: Types::TEXT, nullable: true)]
    private ?string $reason = null;

    #[ORM\Column(type: Types::STRING, length: 32, nullable: true)]
    private ?string $status = null;

    public function getId(): ?int
    {
        return $this->id;
    }

    public function getOrder(): ?Order
    {
        return $this->order;
    }

    public function setOrder(?Order $order): self
    {
        $this->order = $order;

        return $this;
    }

    public function getClient(): ?Client
    {
        return $this->client;
    }

    public function setClient(?Client $client): self
    {
        $this->client = $client;

        return $this;
    }

    public function getType(): ?string
    {
        return $this->type;
    }

    public function setType(?string $type): self
    {
        $this->type = $type;

        return $this;
    }

    public function getReason(): ?string
    {
        return $this->reason;
    }

    public function setReason(?string $reason): self
    {
        $this->reason = $reason;

        return $this;
    }

    public function getStatus(): ?string
    {
        return $this->status;
    }

    public function setStatus(?string $status): self
    {
        $this->status = $status;

        return $this;
    }
}
