namespace Box\Mod\Support\Entity;

use Doctrine\DBAL\Types\Types;
use Doctrine\ORM\Mapping as ORM;

/**
 * A ticket escalation rule (see Box\Mod\Support\TicketEscalation): matches
 * tickets without a reply for the set time, then replies, moves them, changes
 * their priority or assigns them.
 */
#[ORM\Entity]
#[ORM\Table(name: 'support_escalation_rule')]
class SupportEscalationRule
{
    #[ORM\Id]
    #[ORM\GeneratedValue]
    #[ORM\Column(type: Types::BIGINT)]
    /** @phpstan-ignore property.unusedType (Doctrine entity ID is auto-generated by the database) */
    private ?int $id = null;

    #[ORM\Column(type: Types::STRING, length: 100)]
    private ?string $name = null;

    #[ORM\Column(type: Types::BOOLEAN, options: ['default' => true])]
    private bool $active = true;

    /** JSON list<int> of help desk ids (empty: any). */
    #[ORM\Column(type: Types::TEXT)]
    private ?string $helpdesks = null;

    /** JSON list<string> of statuses (empty: any). */
    #[ORM\Column(type: Types::TEXT)]
    private ?string $statuses = null;

    /** JSON list<string> of priority levels (empty: any). */
    #[ORM\Column(type: Types::TEXT)]
    private ?string $priorities = null;

    /** Minutes without a reply before the rule acts. */
    #[ORM\Column(type: Types::INTEGER)]
    private ?int $minutes = null;

    #[ORM\Column(name: 'new_helpdesk_id', type: Types::BIGINT, nullable: true)]
    private ?int $newHelpdeskId = null;

    #[ORM\Column(name: 'new_status', type: Types::STRING, length: 30)]
    private string $newStatus = '';

    #[ORM\Column(name: 'new_priority', type: Types::STRING, length: 10)]
    private string $newPriority = '';

    #[ORM\Column(name: 'assign_to', type: Types::BIGINT, nullable: true)]
    private ?int $assignTo = null;

    /** JSON list<int> of staff ids to email. */
    #[ORM\Column(type: Types::TEXT)]
    private ?string $notify = null;

    #[ORM\Column(type: Types::TEXT)]
    private ?string $reply = null;

    #[ORM\Column(name: 'created_at', type: Types::DATETIME_IMMUTABLE)]
    private ?\DateTimeImmutable $createdAt = null;

    #[ORM\Column(name: 'updated_at', type: Types::DATETIME_IMMUTABLE)]
    private ?\DateTimeImmutable $updatedAt = null;

    public function getId(): ?int
    {
        return $this->id;
    }

    public function getName(): ?string
    {
        return $this->name;
    }

    public function setName(?string $name): self
    {
        $this->name = $name;

        return $this;
    }

    public function isActive(): bool
    {
        return $this->active;
    }

    public function setActive(bool $active): self
    {
        $this->active = $active;

        return $this;
    }

    public function getHelpdesks(): ?string
    {
        return $this->helpdesks;
    }

    public function setHelpdesks(?string $helpdesks): self
    {
        $this->helpdesks = $helpdesks;

        return $this;
    }

    public function getStatuses(): ?string
    {
        return $this->statuses;
    }

    public function setStatuses(?string $statuses): self
    {
        $this->statuses = $statuses;

        return $this;
    }

    public function getPriorities(): ?string
    {
        return $this->priorities;
    }

    public function setPriorities(?string $priorities): self
    {
        $this->priorities = $priorities;

        return $this;
    }

    public function getMinutes(): ?int
    {
        return $this->minutes;
    }

    public function setMinutes(?int $minutes): self
    {
        $this->minutes = $minutes;

        return $this;
    }

    public function getNewHelpdeskId(): ?int
    {
        return $this->newHelpdeskId;
    }

    public function setNewHelpdeskId(?int $newHelpdeskId): self
    {
        $this->newHelpdeskId = $newHelpdeskId;

        return $this;
    }

    public function getNewStatus(): string
    {
        return $this->newStatus;
    }

    public function setNewStatus(string $newStatus): self
    {
        $this->newStatus = $newStatus;

        return $this;
    }

    public function getNewPriority(): string
    {
        return $this->newPriority;
    }

    public function setNewPriority(string $newPriority): self
    {
        $this->newPriority = $newPriority;

        return $this;
    }

    public function getAssignTo(): ?int
    {
        return $this->assignTo;
    }

    public function setAssignTo(?int $assignTo): self
    {
        $this->assignTo = $assignTo;

        return $this;
    }

    public function getNotify(): ?string
    {
        return $this->notify;
    }

    public function setNotify(?string $notify): self
    {
        $this->notify = $notify;

        return $this;
    }

    public function getReply(): ?string
    {
        return $this->reply;
    }

    public function setReply(?string $reply): self
    {
        $this->reply = $reply;

        return $this;
    }

    public function getCreatedAt(): ?\DateTimeImmutable
    {
        return $this->createdAt;
    }

    public function setCreatedAt(?\DateTimeImmutable $createdAt): self
    {
        $this->createdAt = $createdAt;

        return $this;
    }

    public function getUpdatedAt(): ?\DateTimeImmutable
    {
        return $this->updatedAt;
    }

    public function setUpdatedAt(?\DateTimeImmutable $updatedAt): self
    {
        $this->updatedAt = $updatedAt;

        return $this;
    }
}
