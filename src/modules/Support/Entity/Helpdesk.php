namespace Box\Mod\Support\Entity;

use Doctrine\Common\Collections\ArrayCollection;
use Doctrine\Common\Collections\Collection;
use Doctrine\DBAL\Types\Types;
use Doctrine\ORM\Mapping as ORM;
use FOSSBilling\Api\ArrayInterface;
use FOSSBilling\Doctrine\TimestampInterface;
use FOSSBilling\Doctrine\TimestampTrait;

#[ORM\Entity(repositoryClass: \Box\Mod\Support\Repository\HelpdeskRepository::class)]
#[ORM\Table(name: 'support_helpdesk')]
#[ORM\HasLifecycleCallbacks]
class Helpdesk implements ArrayInterface, TimestampInterface
{
    use TimestampTrait;

    /**
     * The DB-level default below only ever applies to a column Doctrine leaves out of its INSERT
     * entirely - and it never does, mapped nullable or not, so a caller omitting a value still
     * gets a literal NULL written, not this default. {@see \Box\Mod\Support\Service::helpdeskCreate()}
     * uses this constant as its own PHP-level fallback for exactly that reason.
     */
    public const int DEFAULT_CLOSE_AFTER_HOURS = 24;

    #[ORM\Id]
    #[ORM\GeneratedValue]
    #[ORM\Column(type: Types::BIGINT)]
    /** @phpstan-ignore property.unusedType (Doctrine entity ID is auto-generated by the database) */
    private ?int $id = null;

    #[ORM\Column(type: Types::STRING, length: 255, nullable: true)]
    private ?string $name = null;

    #[ORM\Column(type: Types::STRING, length: 255, nullable: true)]
    private ?string $email = null;

    #[ORM\Column(name: 'can_reopen', type: Types::BOOLEAN, nullable: true)]
    private ?bool $canReopen = null;

    #[ORM\Column(name: 'close_after', type: Types::SMALLINT, nullable: true, options: ['default' => self::DEFAULT_CLOSE_AFTER_HOURS])]
    private ?int $closeAfter = null;

    #[ORM\Column(type: Types::TEXT, nullable: true)]
    private ?string $signature = null;

    /**
     * @var Collection<int, SupportTicket>
     */
    #[ORM\OneToMany(mappedBy: 'helpdesk', targetEntity: SupportTicket::class)]
    private Collection $tickets;

    public function __construct()
    {
        $this->tickets = new ArrayCollection();
    }

    public function toApiArray(\Box\Mod\Client\Entity\Client|\Box\Mod\Staff\Entity\Admin|\FOSSBilling\Identity\Guest|null $identity = null): array
    {
        if ($identity instanceof \Box\Mod\Staff\Entity\Admin) {
            return [
                'id' => $this->id,
                'name' => $this->name,
                'email' => $this->email,
                'can_reopen' => $this->canReopen,
                'close_after' => $this->closeAfter,
                'signature' => $this->signature,
                'created_at' => $this->createdAt?->format('Y-m-d H:i:s'),
                'updated_at' => $this->updatedAt?->format('Y-m-d H:i:s'),
            ];
        }

        return [
            'id' => $this->id,
            'name' => $this->name,
            'can_reopen' => (bool) $this->canReopen,
        ];
    }

    public function getId(): ?int
    {
        return $this->id;
    }

    public function getName(): ?string
    {
        return $this->name;
    }

    public function setName(?string $name): self
    {
        $this->name = $name;

        return $this;
    }

    public function getEmail(): ?string
    {
        return $this->email;
    }

    public function setEmail(?string $email): self
    {
        $this->email = $email;

        return $this;
    }

    public function canReopen(): bool
    {
        return (bool) $this->canReopen;
    }

    public function setCanReopen(mixed $canReopen): self
    {
        $this->canReopen = $canReopen === null ? null : \FOSSBilling\Utils\Normalizer::normalizeBoolean($canReopen);

        return $this;
    }

    public function getCloseAfter(): ?int
    {
        return $this->closeAfter;
    }

    public function setCloseAfter(int|string|null $closeAfter): self
    {
        $this->closeAfter = $closeAfter === null || $closeAfter === '' ? null : (int) $closeAfter;

        return $this;
    }

    public function getSignature(): ?string
    {
        return $this->signature;
    }

    public function setSignature(?string $signature): self
    {
        $this->signature = $signature;

        return $this;
    }

    /**
     * @return Collection<int, SupportTicket>
     */
    public function getTickets(): Collection
    {
        return $this->tickets;
    }
}
