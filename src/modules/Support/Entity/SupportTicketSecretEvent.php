namespace Box\Mod\Support\Entity;

use Doctrine\DBAL\Types\Types;
use Doctrine\ORM\Mapping as ORM;

/**
 * Audit trail of ticket secret openings, deletions and expiries (see
 * Box\Mod\Support\TicketSecrets). No values, only labels and who did it.
 */
#[ORM\Entity]
#[ORM\Table(name: 'support_ticket_secret_event')]
#[ORM\Index(name: 'support_ticket_secret_event_ticket_idx', columns: ['ticket_id'])]
class SupportTicketSecretEvent
{
    #[ORM\Id]
    #[ORM\GeneratedValue]
    #[ORM\Column(type: Types::BIGINT)]
    /** @phpstan-ignore property.unusedType (Doctrine entity ID is auto-generated by the database) */
    private ?int $id = null;

    #[ORM\Column(name: 'ticket_id', type: Types::BIGINT)]
    private ?int $ticketId = null;

    #[ORM\Column(name: 'secret_label', type: Types::STRING, length: 100)]
    private ?string $secretLabel = null;

    /** opened, deleted or expired. */
    #[ORM\Column(type: Types::STRING, length: 10)]
    private ?string $action = null;

    #[ORM\Column(name: 'admin_id', type: Types::BIGINT, nullable: true)]
    private ?int $adminId = null;

    #[ORM\Column(name: 'client_id', type: Types::BIGINT, nullable: true)]
    private ?int $clientId = null;

    #[ORM\Column(name: 'created_at', type: Types::DATETIME_IMMUTABLE)]
    private ?\DateTimeImmutable $createdAt = null;

    public function getId(): ?int
    {
        return $this->id;
    }

    public function getTicketId(): ?int
    {
        return $this->ticketId;
    }

    public function setTicketId(?int $ticketId): self
    {
        $this->ticketId = $ticketId;

        return $this;
    }

    public function getSecretLabel(): ?string
    {
        return $this->secretLabel;
    }

    public function setSecretLabel(?string $secretLabel): self
    {
        $this->secretLabel = $secretLabel;

        return $this;
    }

    public function getAction(): ?string
    {
        return $this->action;
    }

    public function setAction(?string $action): self
    {
        $this->action = $action;

        return $this;
    }

    public function getAdminId(): ?int
    {
        return $this->adminId;
    }

    public function setAdminId(?int $adminId): self
    {
        $this->adminId = $adminId;

        return $this;
    }

    public function getClientId(): ?int
    {
        return $this->clientId;
    }

    public function setClientId(?int $clientId): self
    {
        $this->clientId = $clientId;

        return $this;
    }

    public function getCreatedAt(): ?\DateTimeImmutable
    {
        return $this->createdAt;
    }

    public function setCreatedAt(?\DateTimeImmutable $createdAt): self
    {
        $this->createdAt = $createdAt;

        return $this;
    }
}
