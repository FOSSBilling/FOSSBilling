namespace Box\Mod\Support\Entity;

use Doctrine\DBAL\Types\Types;
use Doctrine\ORM\Mapping as ORM;

/**
 * Marks an escalation rule as having acted on a ticket for the reply it
 * found (see Box\Mod\Support\TicketEscalation). A rule acts once per reply.
 */
#[ORM\Entity(repositoryClass: \Box\Mod\Support\Repository\SupportEscalationAppliedRepository::class)]
#[ORM\Table(name: 'support_escalation_applied')]
#[ORM\UniqueConstraint(name: 'rule_ticket', columns: ['rule_id', 'ticket_id'])]
class SupportEscalationApplied
{
    #[ORM\Id]
    #[ORM\GeneratedValue]
    #[ORM\Column(type: Types::BIGINT)]
    /** @phpstan-ignore property.unusedType (Doctrine entity ID is auto-generated by the database) */
    private ?int $id = null;

    #[ORM\Column(name: 'rule_id', type: Types::BIGINT)]
    private ?int $ruleId = null;

    #[ORM\Column(name: 'ticket_id', type: Types::BIGINT)]
    private ?int $ticketId = null;

    /** The last reply the rule acted on. */
    #[ORM\Column(name: 'reply_at', type: Types::DATETIME_MUTABLE)]
    private ?\DateTime $replyAt = null;

    #[ORM\Column(name: 'applied_at', type: Types::DATETIME_MUTABLE)]
    private ?\DateTime $appliedAt = null;

    public function getId(): ?int
    {
        return $this->id;
    }

    public function getRuleId(): ?int
    {
        return $this->ruleId;
    }

    public function setRuleId(?int $ruleId): self
    {
        $this->ruleId = $ruleId;

        return $this;
    }

    public function getTicketId(): ?int
    {
        return $this->ticketId;
    }

    public function setTicketId(?int $ticketId): self
    {
        $this->ticketId = $ticketId;

        return $this;
    }

    public function getReplyAt(): ?\DateTime
    {
        return $this->replyAt;
    }

    public function setReplyAt(?\DateTime $replyAt): self
    {
        $this->replyAt = $replyAt;

        return $this;
    }

    public function getAppliedAt(): ?\DateTime
    {
        return $this->appliedAt;
    }

    public function setAppliedAt(?\DateTime $appliedAt): self
    {
        $this->appliedAt = $appliedAt;

        return $this;
    }
}
