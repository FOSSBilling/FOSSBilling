namespace Box\Mod\Support\Entity;

use Box\Mod\Support\Repository\TicketNotificationRepository;
use Doctrine\DBAL\Types\Types;
use Doctrine\ORM\Mapping as ORM;
use FOSSBilling\Doctrine\TimestampTrait;
use FOSSBilling\Interfaces\TimestampInterface;

#[ORM\Entity(repositoryClass: TicketNotificationRepository::class)]
#[ORM\Table(name: 'support_ticket_notification')]
#[ORM\Index(name: 'ticket_notification_client_read_idx', columns: ['client_id', 'read_at', 'id'])]
#[ORM\HasLifecycleCallbacks]
class TicketNotification implements TimestampInterface
{
    use TimestampTrait;

    #[ORM\Id]
    #[ORM\GeneratedValue]
    #[ORM\Column(type: Types::BIGINT)]
    /** @phpstan-ignore property.unusedType (Doctrine entity ID is auto-generated by the database) */
    private ?int $id = null;

    #[ORM\Column(name: 'client_id', type: Types::BIGINT)]
    private int $clientId;

    #[ORM\OneToOne(targetEntity: SupportTicketMessage::class)]
    #[ORM\JoinColumn(name: 'message_id', referencedColumnName: 'id', nullable: false, onDelete: 'CASCADE')]
    private SupportTicketMessage $message;

    #[ORM\Column(name: 'read_at', type: Types::DATETIME_IMMUTABLE, nullable: true)]
    private ?\DateTimeImmutable $readAt = null;

    public function __construct(int $clientId, SupportTicketMessage $message)
    {
        $this->clientId = $clientId;
        $this->message = $message;
    }

    public function getId(): ?int
    {
        return $this->id;
    }

    public function getClientId(): int
    {
        return $this->clientId;
    }

    public function getMessage(): SupportTicketMessage
    {
        return $this->message;
    }

    public function getReadAt(): ?\DateTimeImmutable
    {
        return $this->readAt;
    }

    public function setReadAt(?\DateTimeImmutable $readAt): self
    {
        $this->readAt = $readAt;

        return $this;
    }
}
