namespace Box\Mod\Support\Entity;

use Doctrine\DBAL\Types\Types;
use Doctrine\ORM\Mapping as ORM;

/**
 * A file attached to a support ticket message (see Box\Mod\Support\TicketFiles).
 * The file itself lives outside the web root; this row is its metadata.
 * message_id NULL means "waiting to be sent": bound to the message on save.
 */
#[ORM\Entity]
#[ORM\Table(name: 'support_ticket_file')]
#[ORM\Index(name: 'support_ticket_file_message_idx', columns: ['message_id'])]
#[ORM\Index(name: 'support_ticket_file_ticket_idx', columns: ['ticket_id'])]
#[ORM\Index(name: 'support_ticket_file_client_idx', columns: ['client_id'])]
#[ORM\Index(name: 'support_ticket_file_waiting_idx', columns: ['session_hash', 'message_id'])]
#[ORM\Index(name: 'support_ticket_file_uploader_idx', columns: ['uploader_kind', 'uploader_id', 'created_at'])]
#[ORM\UniqueConstraint(name: 'support_ticket_file_token_uniq', columns: ['token'])]
class SupportTicketFile
{
    #[ORM\Id]
    #[ORM\GeneratedValue]
    #[ORM\Column(type: Types::BIGINT)]
    /** @phpstan-ignore property.unusedType (Doctrine entity ID is auto-generated by the database) */
    private ?int $id = null;

    /** Public id (hex random_bytes(16)); the API and download URLs use it. */
    #[ORM\Column(type: Types::STRING, length: 32)]
    private ?string $token = null;

    #[ORM\Column(name: 'ticket_id', type: Types::BIGINT, nullable: true)]
    private ?int $ticketId = null;

    #[ORM\Column(name: 'message_id', type: Types::BIGINT, nullable: true)]
    private ?int $messageId = null;

    #[ORM\Column(name: 'client_id', type: Types::BIGINT)]
    private ?int $clientId = null;

    /** client, admin or mail. */
    #[ORM\Column(name: 'uploader_kind', type: Types::STRING, length: 10)]
    private ?string $uploaderKind = null;

    #[ORM\Column(name: 'uploader_id', type: Types::BIGINT)]
    private ?int $uploaderId = null;

    /** Browser session the waiting file belongs to ('' for mail). */
    #[ORM\Column(name: 'session_hash', type: Types::STRING, length: 64)]
    private ?string $sessionHash = null;

    #[ORM\Column(type: Types::STRING, length: 191)]
    private ?string $name = null;

    #[ORM\Column(type: Types::STRING, length: 100)]
    private ?string $mime = null;

    #[ORM\Column(type: Types::INTEGER)]
    private ?int $size = null;

    #[ORM\Column(name: 'created_at', type: Types::DATETIME_IMMUTABLE)]
    private ?\DateTimeImmutable $createdAt = null;

    #[ORM\Column(name: 'attached_at', type: Types::DATETIME_IMMUTABLE, nullable: true)]
    private ?\DateTimeImmutable $attachedAt = null;

    #[ORM\Column(name: 'removed_at', type: Types::DATETIME_IMMUTABLE, nullable: true)]
    private ?\DateTimeImmutable $removedAt = null;

    #[ORM\Column(name: 'removed_by', type: Types::BIGINT, nullable: true)]
    private ?int $removedBy = null;

    /** staff or expired. */
    #[ORM\Column(name: 'removed_reason', type: Types::STRING, length: 20, nullable: true)]
    private ?string $removedReason = null;

    public function getId(): ?int
    {
        return $this->id;
    }

    public function getToken(): ?string
    {
        return $this->token;
    }

    public function setToken(?string $token): self
    {
        $this->token = $token;

        return $this;
    }

    public function getTicketId(): ?int
    {
        return $this->ticketId;
    }

    public function setTicketId(?int $ticketId): self
    {
        $this->ticketId = $ticketId;

        return $this;
    }

    public function getMessageId(): ?int
    {
        return $this->messageId;
    }

    public function setMessageId(?int $messageId): self
    {
        $this->messageId = $messageId;

        return $this;
    }

    public function getClientId(): ?int
    {
        return $this->clientId;
    }

    public function setClientId(?int $clientId): self
    {
        $this->clientId = $clientId;

        return $this;
    }

    public function getUploaderKind(): ?string
    {
        return $this->uploaderKind;
    }

    public function setUploaderKind(?string $uploaderKind): self
    {
        $this->uploaderKind = $uploaderKind;

        return $this;
    }

    public function getUploaderId(): ?int
    {
        return $this->uploaderId;
    }

    public function setUploaderId(?int $uploaderId): self
    {
        $this->uploaderId = $uploaderId;

        return $this;
    }

    public function getSessionHash(): ?string
    {
        return $this->sessionHash;
    }

    public function setSessionHash(?string $sessionHash): self
    {
        $this->sessionHash = $sessionHash;

        return $this;
    }

    public function getName(): ?string
    {
        return $this->name;
    }

    public function setName(?string $name): self
    {
        $this->name = $name;

        return $this;
    }

    public function getMime(): ?string
    {
        return $this->mime;
    }

    public function setMime(?string $mime): self
    {
        $this->mime = $mime;

        return $this;
    }

    public function getSize(): ?int
    {
        return $this->size;
    }

    public function setSize(?int $size): self
    {
        $this->size = $size;

        return $this;
    }

    public function getCreatedAt(): ?\DateTimeImmutable
    {
        return $this->createdAt;
    }

    public function setCreatedAt(?\DateTimeImmutable $createdAt): self
    {
        $this->createdAt = $createdAt;

        return $this;
    }

    public function getAttachedAt(): ?\DateTimeImmutable
    {
        return $this->attachedAt;
    }

    public function setAttachedAt(?\DateTimeImmutable $attachedAt): self
    {
        $this->attachedAt = $attachedAt;

        return $this;
    }

    public function getRemovedAt(): ?\DateTimeImmutable
    {
        return $this->removedAt;
    }

    public function setRemovedAt(?\DateTimeImmutable $removedAt): self
    {
        $this->removedAt = $removedAt;

        return $this;
    }

    public function getRemovedBy(): ?int
    {
        return $this->removedBy;
    }

    public function setRemovedBy(?int $removedBy): self
    {
        $this->removedBy = $removedBy;

        return $this;
    }

    public function getRemovedReason(): ?string
    {
        return $this->removedReason;
    }

    public function setRemovedReason(?string $removedReason): self
    {
        $this->removedReason = $removedReason;

        return $this;
    }
}
