namespace Box\Mod\Support\Entity;

use Doctrine\DBAL\Types\Types;
use Doctrine\ORM\Mapping as ORM;

/**
 * A secret a client attached to a ticket (see Box\Mod\Support\TicketSecrets).
 * `data` is encrypted; only label/kind are plaintext metadata. Values are
 * never embedded in ticket payloads or emails, and vanish when the ticket
 * closes; the audit events survive closing but not deletion.
 */
#[ORM\Entity]
#[ORM\Table(name: 'support_ticket_secret')]
#[ORM\Index(name: 'support_ticket_secret_ticket_idx', columns: ['ticket_id'])]
#[ORM\Index(name: 'support_ticket_secret_created_idx', columns: ['created_at'])]
class SupportTicketSecret
{
    #[ORM\Id]
    #[ORM\GeneratedValue]
    #[ORM\Column(type: Types::BIGINT)]
    /** @phpstan-ignore property.unusedType (Doctrine entity ID is auto-generated by the database) */
    private ?int $id = null;

    #[ORM\Column(name: 'ticket_id', type: Types::BIGINT)]
    private ?int $ticketId = null;

    /** server or other. */
    #[ORM\Column(type: Types::STRING, length: 10)]
    private ?string $kind = null;

    #[ORM\Column(type: Types::STRING, length: 100)]
    private ?string $label = null;

    /** Encrypted field set. */
    #[ORM\Column(type: Types::TEXT)]
    private ?string $data = null;

    #[ORM\Column(name: 'added_by_client_id', type: Types::BIGINT, nullable: true)]
    private ?int $addedByClientId = null;

    #[ORM\Column(name: 'created_at', type: Types::DATETIME_IMMUTABLE)]
    private ?\DateTimeImmutable $createdAt = null;

    public function getId(): ?int
    {
        return $this->id;
    }

    public function getTicketId(): ?int
    {
        return $this->ticketId;
    }

    public function setTicketId(?int $ticketId): self
    {
        $this->ticketId = $ticketId;

        return $this;
    }

    public function getKind(): ?string
    {
        return $this->kind;
    }

    public function setKind(?string $kind): self
    {
        $this->kind = $kind;

        return $this;
    }

    public function getLabel(): ?string
    {
        return $this->label;
    }

    public function setLabel(?string $label): self
    {
        $this->label = $label;

        return $this;
    }

    public function getData(): ?string
    {
        return $this->data;
    }

    public function setData(?string $data): self
    {
        $this->data = $data;

        return $this;
    }

    public function getAddedByClientId(): ?int
    {
        return $this->addedByClientId;
    }

    public function setAddedByClientId(?int $addedByClientId): self
    {
        $this->addedByClientId = $addedByClientId;

        return $this;
    }

    public function getCreatedAt(): ?\DateTimeImmutable
    {
        return $this->createdAt;
    }

    public function setCreatedAt(?\DateTimeImmutable $createdAt): self
    {
        $this->createdAt = $createdAt;

        return $this;
    }
}
